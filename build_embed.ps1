#---------------------------------------------------------------------
# build_embed.ps1
# Developer tool, not deployed.  Turns FastPlotEngine.cs,
# FastPlot_compose.ps1 and FastPlot_monitor.ps1 into
# includes\FastPlot_embed.H, so the compiled FastPlot_panel_01.4do
# carries them and writes them out at run time - the .4do is the only
# file users need.
#
# Run after editing either file, then compile the macro:
#   powershell -ExecutionPolicy Bypass -File build_embed.ps1
#---------------------------------------------------------------------
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$out = Join-Path $here 'includes\FastPlot_embed.H'
$chunk = 200   # lines per 12dPL function

function Embed([string]$file, [string]$prefix, [System.Text.StringBuilder]$sb) {
    $lines = [IO.File]::ReadAllLines((Join-Path $here $file))
    foreach ($l in $lines) {
        foreach ($ch in $l.ToCharArray()) {
            if ([int]$ch -gt 126) { throw "$file has a non-ASCII character ('$ch'); cc4d cannot carry it" }
        }
    }
    $n = [Math]::Ceiling($lines.Count / $chunk)
    for ($c = 0; $c -lt $n; $c++) {
        [void]$sb.AppendLine("void ${prefix}_$($c + 1)(File f)")
        [void]$sb.AppendLine('{')
        $end = [Math]::Min($lines.Count, ($c + 1) * $chunk)
        for ($i = $c * $chunk; $i -lt $end; $i++) {
            $t = $lines[$i].Replace("`t", '    ').Replace('\', '\\').Replace('"', '\"')
            [void]$sb.AppendLine("    File_write_line(f, `"$t`");")
        }
        [void]$sb.AppendLine('}')
        [void]$sb.AppendLine('')
    }
    [void]$sb.AppendLine("Integer write_$prefix(Text path)")
    [void]$sb.AppendLine('{')
    [void]$sb.AppendLine('    File f;')
    [void]$sb.AppendLine('    if(File_open(path, "w", "", f) != 0) return 1;')
    for ($c = 0; $c -lt $n; $c++) { [void]$sb.AppendLine("    ${prefix}_$($c + 1)(f);") }
    [void]$sb.AppendLine('    File_close(f);')
    [void]$sb.AppendLine('    return 0;')
    [void]$sb.AppendLine('}')
    [void]$sb.AppendLine('')
    return $lines.Count
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('//---------------------------------------------------------------------')
[void]$sb.AppendLine('// FastPlot_embed.H - GENERATED by build_embed.ps1, do not edit.')
[void]$sb.AppendLine('// FastPlotEngine.cs, FastPlot_compose.ps1 and FastPlot_monitor.ps1 as')
[void]$sb.AppendLine('// File_write_line calls, written out by write_engine_cs / _ps1 / _mon.')
[void]$sb.AppendLine('//---------------------------------------------------------------------')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#ifndef FASTPLOT_EMBED_H')
[void]$sb.AppendLine('#define FASTPLOT_EMBED_H')
[void]$sb.AppendLine('')
$a = Embed 'FastPlotEngine.cs' 'engine_cs' $sb
$b = Embed 'FastPlot_compose.ps1' 'engine_ps1' $sb
$c = Embed 'FastPlot_monitor.ps1' 'engine_mon' $sb
[void]$sb.AppendLine('#endif')
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $out ($a + $b + $c lines embedded)"
